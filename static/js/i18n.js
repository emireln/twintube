const langLabels = { en: 'EN', pt: 'PT' };

function detectBrowserLanguage() {
  const langs = navigator.languages?.length
    ? navigator.languages
    : [navigator.language || 'en'];
  for (const lang of langs) {
    const code = (lang || '').toLowerCase().split('-')[0];
    if (code === 'pt') return 'pt';
    if (code === 'en') return 'en';
  }
  return 'en';
}

let currentLang = localStorage.getItem('twintube_lang');
if (!currentLang || !translations[currentLang]) {
  currentLang = detectBrowserLanguage();
  localStorage.setItem('twintube_lang', currentLang);
}

export function getLanguageLabel(lang) {
  const code = lang || currentLang;
  return code === 'pt' ? translations.pt.portuguese : translations.en.english;
}

export function getLanguage() {
  return currentLang;
}

export function setLanguage(lang) {
  if (!translations[lang]) return;
  currentLang = lang;
  localStorage.setItem('twintube_lang', lang);
  updateDOMTranslations();
  window.dispatchEvent(new CustomEvent('twintube:languagechange', { detail: { lang } }));
}

export function t(key, fallbackOrVars = '') {
  const dict = translations[currentLang] || translations.en;
  let fallback = '';
  let vars = null;
  if (fallbackOrVars && typeof fallbackOrVars === 'object') {
    vars = fallbackOrVars;
  } else {
    fallback = fallbackOrVars;
  }
  let str = dict[key] || translations.en[key] || fallback || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = String(str).replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
  }
  return str;
}

